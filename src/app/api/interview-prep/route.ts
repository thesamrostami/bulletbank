import { NextRequest, NextResponse } from 'next/server'
import { callClaude } from '@/lib/ai-client'
import { parseAIJson, extractText } from '@/lib/parse-ai-json'
import { validateInterviewQuestions } from '@/lib/validate-ai-output'
import { createServerSupabaseClient } from '@/lib/supabase-server'
import { INTERVIEW_QUESTIONS_PROMPT } from '@/lib/prompts'
import { atomicDeductCredits, insufficientCreditsResponse, refundCredits } from '@/lib/rate-limit'
import { checkRateLimitWithDb, rateLimitResponse } from '@/lib/request-rate-limit'
import { asStoredPrep, type PrepVersion, type StoredPrep } from '@/lib/interview-prep'
import type { DebriefInsight } from '@/types'

type SnapshotBullet = {
  bullet_id: string
  text: string
  type: string
  has_metric?: boolean
  metric_text?: string | null
  star_story?: string | null
}

export async function POST(req: NextRequest) {
  // Outer try/catch: req.json() on a malformed body would otherwise throw unhandled
  try {
  const supabase = await createServerSupabaseClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized', code: 'UNAUTHORIZED' }, { status: 401 })

  const rl = await checkRateLimitWithDb(supabase, `interview-prep:${user.id}`, { limit: 20, windowMs: 60_000 })
  if (!rl.allowed) return rateLimitResponse(rl.resetAt)

  const { jobId, forceRegenerate } = await req.json()

  const { data: job, error: jobError } = await supabase
    .from('jobs')
    .select('*')
    .eq('id', jobId)
    .eq('user_id', user.id)
    .single()

  if (jobError || !job) {
    return NextResponse.json({ error: 'Job not found' }, { status: 404 })
  }

  const cached = asStoredPrep(job.interview_prep)
  if (!forceRegenerate && cached) {
    return NextResponse.json(cached)
  }

  const creditResult = await atomicDeductCredits(supabase, user.id, 'interview_prep', jobId)
  if (!creditResult.success) return insufficientCreditsResponse(creditResult, 'interview_prep')

  const archetype = (job.fit_analysis as { archetype?: string } | null)?.archetype || null
  let pastInsights: DebriefInsight[] = []

  if (archetype) {
    const { data: insights } = await supabase
      .from('debrief_insights')
      .select('*')
      .eq('user_id', user.id)
      .eq('role_archetype', archetype)
      .order('created_at', { ascending: false })
      .limit(20)
    pastInsights = (insights || []) as DebriefInsight[]
  }

  const questionCounts = new Map<string, number>()
  pastInsights.forEach(i => {
    const key = i.question.toLowerCase().trim()
    questionCounts.set(key, (questionCounts.get(key) || 0) + 1)
  })
  const repeatedQuestions = pastInsights.filter(i =>
    (questionCounts.get(i.question.toLowerCase().trim()) || 0) >= 2
  )
  const pastInsightsSummary = repeatedQuestions.map(i => ({
    question: i.question,
    outcome: i.outcome,
    count: questionCounts.get(i.question.toLowerCase().trim()) || 1,
  }))

  const documentNote = (job.own_cv_url && !job.own_cv_text)
    ? `\nNote: The candidate used their own uploaded CV (not generated by the system). Interview prep should be based on the job requirements and any bullet bank bullets that match, rather than specific CV bullets.\n`
    : ''

  let applicationBullets: SnapshotBullet[] = []

  if (job.cv_snapshot) {
    const snap = job.cv_snapshot as {
      summaryBullets?: SnapshotBullet[]
      highlightBullets?: SnapshotBullet[]
      workExperiences?: Array<{ bullets?: SnapshotBullet[] }>
    }
    applicationBullets = [
      ...(snap.summaryBullets || []),
      ...(snap.highlightBullets || []),
      ...(snap.workExperiences || []).flatMap((we) => we.bullets || []),
    ]
  } else if ((job.cv_bullet_ids || []).length > 0) {
    const { data } = await supabase
      .from('bullet_bank')
      .select('bullet_id, text, type, has_metric, metric_text, star_story')
      .eq('user_id', user.id)
      .in('bullet_id', job.cv_bullet_ids)
    applicationBullets = (data || []) as SnapshotBullet[]
  }

  const bulletSummary = applicationBullets.map((b) => ({
    bullet_id: b.bullet_id,
    text: b.text,
    type: b.type || 'highlight',
  }))

  try {
    const prompt = INTERVIEW_QUESTIONS_PROMPT(
      { company: job.company, role: job.role, requirements: job.requirements || [] },
      bulletSummary,
      job.cover_letter || '',
      documentNote,
      job.own_cv_text ? job.own_cv_text.slice(0, 5000) : undefined,
      pastInsightsSummary.length > 0 ? pastInsightsSummary : undefined
    )

    const message = await callClaude({
      system: prompt.system,
      userContent: prompt.user,
      maxTokens: 4096,
      temperature: 'creative',
    })

    const questions = parseAIJson(extractText(message))
    validateInterviewQuestions(questions)

    const newVersion: PrepVersion = {
      generatedAt: new Date().toISOString(),
      questions,
      applicationBullets,
      metricBullets: applicationBullets.filter((b) => b.has_metric),
      coverLetter: job.cover_letter ?? null,
      gaps: (job.fit_analysis as { gaps?: string[] } | null)?.gaps || [],
    }

    const prevHistory = cached ? [cached.current, ...cached.history].slice(0, 4) : []
    const storedPrep: StoredPrep = {
      current: newVersion,
      history: prevHistory,
    }

    const { error: updateError } = await supabase
      .from('jobs')
      .update({ interview_prep: storedPrep as unknown as Record<string, unknown> })
      .eq('id', jobId)
      .eq('user_id', user.id)

    if (updateError) {
      console.error('[interview-prep] Failed to cache prep:', updateError.message)
    }

    return NextResponse.json(storedPrep)
  } catch (err) {
    console.error('[interview-prep]', err)
    // Refund: the user was charged but the AI call/parse failed
    await refundCredits(supabase, user.id, 'interview_prep', jobId).catch(() => {})
    if (err instanceof Error && (err.message.startsWith('Failed to parse') || err.message.startsWith('AI returned'))) {
      return NextResponse.json({ error: 'AI returned invalid structure — please retry', code: 'PARSE_ERROR' }, { status: 500 })
    }
    return NextResponse.json({ error: 'Failed to generate interview prep', code: 'INTERNAL_ERROR' }, { status: 500 })
  }
  } catch (err) {
    console.error('[interview-prep POST]', err)
    return NextResponse.json({ error: 'An unexpected error occurred', code: 'INTERNAL_ERROR' }, { status: 500 })
  }
}
